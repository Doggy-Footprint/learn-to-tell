#!/usr/bin/env node
import { appendFile, mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { realpathSync } from "node:fs";
import { lttHome } from "../server/server.mjs";
import yaml from "./vendor/js-yaml.mjs";
import { ID_RE, cmp, toDay } from "./lib/common.mjs";
import { check } from "./lib/check.mjs";
import { derive } from "./lib/derive.mjs";
import { find } from "./lib/find.mjs";

const GENERATED = "<!-- generated by ltt-map: edit the lesson record or decisions.jsonl, not this file -->";
const SWEEP_THRESHOLD = 10;

const today = () => toDay(new Date());
const stableJson = (value) => JSON.stringify(value, null, 2) + "\n";
const oneLine = (text) => String(text ?? "").replace(/\s+/g, " ").trim();

async function readOptional(file) {
  try {
    return await readFile(file, "utf8");
  } catch (err) {
    if (err.code === "ENOENT") return null;
    throw err;
  }
}

async function readLessons(home) {
  let names;
  try {
    names = (await readdir(join(home, "lessons"), { withFileTypes: true })).filter((d) => d.isDirectory()).map((d) => d.name).sort(cmp);
  } catch (err) {
    if (err.code === "ENOENT") return [];
    throw err;
  }
  const lessons = [];
  for (const name of names) {
    const text = await readOptional(join(home, "lessons", name, "result.md"));
    if (text !== null) lessons.push({ path: `lessons/${name}/result.md`, text });
  }
  return lessons;
}

async function load(home, day) {
  const decisions = (await readOptional(join(home, "decisions.jsonl"))) ?? "";
  const derived = derive(await readLessons(home), decisions, day);
  return { ...derived, ...check(derived) };
}

async function writeIfChanged(file, content) {
  if ((await readOptional(file)) !== content) await writeFile(file, content);
}

function mapMarkdown(concepts) {
  const rows = concepts.flatMap((c) => c.domains.map((domain) => ({ domain, c })));
  rows.sort((a, b) => cmp(a.domain, b.domain) || a.c.level - b.c.level || cmp(a.c.title, b.c.title) || cmp(a.c.id, b.c.id));
  const cell = (s) => String(s).replace(/\|/g, "\\|");
  return [
    "# Learn to Tell map",
    GENERATED,
    "",
    "| domain | level | title | status | freshness | last date | lessons |",
    "| --- | --- | --- | --- | --- | --- | --- |",
    ...rows.map(({ domain, c }) => `| ${domain} | ${c.level} | ${cell(c.title)} | ${c.status} | ${c.freshness} | ${c.last_date} | ${c.lessons.join(", ")} |`),
    "",
  ].join("\n");
}

export async function rebuild({ home = lttHome(), today: day = today() } = {}) {
  const result = await load(home, day);
  await mkdir(join(home, "concepts"), { recursive: true });
  const wanted = new Set();
  for (const c of result.concepts) {
    if (!ID_RE.test(c.id)) continue;
    wanted.add(`${c.id}.md`);
    await writeIfChanged(join(home, "concepts", `${c.id}.md`), `---\n${yaml.dump(c, { sortKeys: true, lineWidth: -1 })}---\n${GENERATED}\n`);
  }
  for (const name of await readdir(join(home, "concepts"))) {
    if (name.endsWith(".md") && !wanted.has(name)) await rm(join(home, "concepts", name));
  }
  await writeIfChanged(join(home, "map.md"), mapMarkdown(result.concepts));
  await writeIfChanged(join(home, "map-data.json"), stableJson({ concepts: result.concepts, edges: result.edges, frontier: result.frontier }));
  return result;
}

function report(result, out) {
  for (const e of result.errors) out(`error ${e}`);
  for (const w of result.warnings) out(`warning ${w}`);
}

function resolveId(result, id) {
  return result.merged[id] ?? id;
}

function describe(c) {
  return `${c.id} | ${oneLine(c.title)} | ${oneLine(c.definition)} | domains=${c.domains.join(",")} level=${c.level} status=${c.status} freshness=${c.freshness} last=${c.last_date}${c.merged_from.length ? ` merged_from=${c.merged_from.join(",")}` : ""}`;
}

function show(result, rawId, depth, out) {
  const id = resolveId(result, rawId);
  const byId = new Map(result.concepts.map((c) => [c.id, c]));
  const frontier = new Set(result.frontier.map((f) => f.id));
  if (!byId.has(id) && !frontier.has(id)) return false;
  const line = (nid) => (byId.has(nid) ? describe(byId.get(nid)) : `${nid} | (not yet learned) | frontier`);
  out(line(id));
  const seen = new Set([id]);
  let layer = [{ id, via: "" }];
  for (let d = 0; d < depth; d++) {
    const next = [];
    for (const { id: cur, via } of layer) {
      for (const [rel, test, pick] of [["requires", (e) => e.to === cur, (e) => e.from], ["leads_to", (e) => e.from === cur, (e) => e.to]]) {
        for (const nid of result.edges.filter(test).map(pick).sort(cmp)) {
          if (seen.has(nid)) continue;
          seen.add(nid);
          const path = via ? `${via}>${rel}` : rel;
          out(`${path}: ${line(nid)}`);
          next.push({ id: nid, via: path });
        }
      }
    }
    layer = next;
  }
  return true;
}

async function readSwept(home) {
  try {
    const swept = JSON.parse((await readOptional(join(home, "map-state.json"))) ?? "{}").swept;
    return Array.isArray(swept) ? swept.filter((s) => typeof s === "string") : [];
  } catch {
    return [];
  }
}

// Standalone lessons (claude.ai, no local home) carry their result.md inside the artifact HTML so a later
// Claude Code session can bring it into the map; a bare result.md is accepted for the paste fallback.
const RESULT_BLOCK = /<script\b[^>]*\btype=["']application\/ltt-result["'][^>]*>([\s\S]*?)<\/script>/i;

function extractResult(text) {
  const block = RESULT_BLOCK.exec(text);
  const body = (block ? block[1] : text).replace(/^\s*\n/, "").replace(/\s+$/, "") + "\n";
  const fm = /^---\r?\n([\s\S]*?)\r?\n---/.exec(body);
  if (!fm) return { error: block ? "result block has no frontmatter" : "no ltt-result block or result.md frontmatter" };
  let meta;
  try {
    meta = yaml.load(fm[1]);
  } catch (e) {
    return { error: `frontmatter: ${e.message}` };
  }
  const lesson = meta && typeof meta === "object" ? String(meta.lesson ?? "") : "";
  if (!ID_RE.test(lesson)) return { error: `invalid lesson id ${JSON.stringify(lesson)}` };
  return { lesson, body, html: block ? text : null };
}

async function importLesson(home, file, day, out, err) {
  const found = extractResult(await readFile(file, "utf8"));
  if (found.error) {
    err(`error ${file}: ${found.error}`);
    return 1;
  }
  const dir = join(home, "lessons", found.lesson);
  const existing = await readOptional(join(dir, "result.md"));
  if (existing !== null) {
    out(existing === found.body ? `skip ${found.lesson}: already imported` : `skip ${found.lesson}: lessons/${found.lesson}/result.md exists and differs`);
    return 0;
  }
  await mkdir(dir, { recursive: true });
  await writeFile(join(dir, "result.md"), found.body);
  if (found.html !== null) await writeFile(join(dir, "lesson.html"), found.html);
  out(`imported ${found.lesson}`);
  const result = await rebuild({ home, today: day });
  report(result, out);
  return result.errors.length ? 1 : 0;
}

function usage(err) {
  err("usage: ltt-map rebuild | import <lesson.html|result.md> | find <text> [--domain d] [-k n] | show <id> [--depth 1|2] | decide merge|link|reject <id> <id> | check | sweep | sweep-done <id>...");
  return 2;
}

function parseFlags(args, spec) {
  const flags = {};
  const rest = [];
  for (let i = 0; i < args.length; i++) {
    if (spec[args[i]]) flags[spec[args[i]]] = args[++i];
    else rest.push(args[i]);
  }
  return { flags, rest };
}

export async function run(argv, { home = lttHome(), today: day = today(), out = console.log, err = console.error } = {}) {
  const [cmd, ...args] = argv;
  switch (cmd) {
    case "rebuild": {
      const result = await rebuild({ home, today: day });
      report(result, out);
      return result.errors.length ? 1 : 0;
    }
    case "import": {
      if (args.length !== 1) return usage(err);
      return await importLesson(home, args[0], day, out, err);
    }
    case "check": {
      const result = await load(home, day);
      report(result, out);
      return result.errors.length ? 1 : 0;
    }
    case "find": {
      const { flags, rest } = parseFlags(args, { "--domain": "domain", "-k": "k" });
      const k = flags.k === undefined ? 5 : Number(flags.k);
      if (!rest.length || !Number.isInteger(k) || k < 0) return usage(err);
      const result = await load(home, day);
      for (const h of find(result.concepts, rest.join(" "), { k, domain: flags.domain })) {
        out(`${h.id} | ${oneLine(h.title)} | ${oneLine(h.definition)} | ${Number(h.score.toFixed(3))}${h.exact ? " | exact" : ""}`);
      }
      return 0;
    }
    case "show": {
      const { flags, rest } = parseFlags(args, { "--depth": "depth" });
      const depth = flags.depth === undefined ? 1 : Number(flags.depth);
      if (rest.length !== 1 || (depth !== 1 && depth !== 2)) return usage(err);
      const result = await load(home, day);
      if (!show(result, rest[0], depth, out)) {
        err(`unknown concept ${rest[0]}`);
        return 2;
      }
      return 0;
    }
    case "decide": {
      const [op, ...ids0] = args;
      const ids = ids0.length === 3 && ["into", "to"].includes(ids0[1]) ? [ids0[0], ids0[2]] : ids0;
      if (!["merge", "link", "reject"].includes(op) || ids.length !== 2) return usage(err);
      const result = await load(home, day);
      const known = new Set([...result.concepts.map((c) => c.id), ...result.frontier.map((f) => f.id), ...Object.keys(result.merged)]);
      for (const id of ids) {
        if (!known.has(id)) {
          err(`unknown concept ${id}`);
          return 2;
        }
      }
      const fields = { merge: ["from", "into"], link: ["from", "to"], reject: ["a", "b"] }[op];
      const line = { op, [fields[0]]: ids[0], [fields[1]]: ids[1], date: day };
      await mkdir(home, { recursive: true });
      await appendFile(join(home, "decisions.jsonl"), JSON.stringify(line) + "\n");
      const after = await rebuild({ home, today: day });
      report(after, out);
      return after.errors.length ? 1 : 0;
    }
    case "sweep": {
      const result = await load(home, day);
      const swept = new Set(await readSwept(home));
      const slim = (c) => ({ id: c.id, title: c.title, definition: c.definition, domains: c.domains, level: c.level });
      const fresh = result.concepts.filter((c) => !swept.has(c.id));
      out(stableJson({
        due: fresh.length >= SWEEP_THRESHOLD,
        new: fresh.map(slim),
        existing: result.concepts.filter((c) => swept.has(c.id)).map(slim),
        edges: result.edges,
        rejected: result.rejected,
      }).trimEnd());
      return 0;
    }
    case "sweep-done": {
      if (!args.length) return usage(err);
      const result = await load(home, day);
      const ids = new Set(result.concepts.map((c) => c.id));
      const resolved = args.map((id) => resolveId(result, id));
      const bad = args.find((id, i) => !ids.has(resolved[i]));
      if (bad !== undefined) {
        err(`unknown concept ${bad}`);
        return 2;
      }
      const swept = [...new Set([...(await readSwept(home)), ...resolved])].sort(cmp);
      await mkdir(home, { recursive: true });
      await writeFile(join(home, "map-state.json"), stableJson({ swept }));
      return 0;
    }
    default:
      return usage(err);
  }
}

if (process.argv[1] && realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exitCode = await run(process.argv.slice(2));
}
